export const QUICK_LINK_ICON_NAMES = Object.keys(QUICK_LINK_ICONS);

export function isIconName(name: unknown): name is string {
  return typeof name === 'string' && name in QUICK_LINK_ICONS;
}

const svg = (inner: string, size: number) =>
  `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;

// '' if unknown. Safe to inject: the markup is this module's constants.
export function iconSvg(name: unknown, size = 18): string {
  if (!isIconName(name)) return '';
  return svg(QUICK_LINK_ICONS[name], size);
}

